// Run: node src/tests/economy.mjs
// Actual current public-sector finance and finite local transactions.
import assert from 'node:assert/strict';
import { TownLife, GOODS } from '../world/life.js';
import { placePanel } from '../ui/townpanels.js';
const homes=Array.from({length:188},(_,i)=>({coordinate:String.fromCharCode(65+i%26)+(1+Math.floor(i/26)),name:'Home '+i,door:{x:i%26*26,z:Math.floor(i/26)*46}}));
const t=new TownLife({homes});
assert.equal(t.villagers.length,38);
assert.equal(t.civic.player.wallet,75);
const total=()=>t.civic.player.wallet+t.civic.player.bank+t.civic.treasury+
 t.civic.finance.federal+t.civic.finance.state+
 t.villagers.reduce((n,v)=>n+v.wallet,0)+
 [...t.places.values()].reduce((n,p)=>n+(p.till||0)+(p.operating||0),0);
t.minute=11*60;
const initial=total(),shop=t.place('store'),before=t.shelves(shop).bread,price=GOODS.bread.price;
assert.match(t.buyItem('store','bread'),/You buy/);
assert.equal(t.civic.player.wallet,75-price);
assert.equal(t.civic.player.bag.bread,1);
assert.equal(t.shelves(shop).bread,before-1);
assert(Math.abs(total()-initial)<0.001,'local purchase must conserve accounted funds');
assert.match(t.sellItem('store','bread'),/buys it back/);
assert.equal(t.civic.player.bag.bread,0);
assert(Math.abs(total()-initial)<0.001,'buyback must conserve accounted funds');
const wallet=t.civic.player.wallet,bank=t.civic.player.bank;
assert.match(t.bank('deposit',10),/Deposited/);
assert.equal(t.civic.player.wallet,wallet-10);
assert.equal(t.civic.player.bank,bank+10);
assert.match(t.bank('withdraw',10),/Withdrew/);
assert.equal(t.civic.player.wallet,wallet);
assert.equal(t.civic.player.bank,bank);
assert(Math.abs(total()-initial)<0.001,'bank transfers must conserve funds');
t.civic.player.wallet=0;
assert.match(t.buyItem('store','bread'),/need/);
assert.equal(t.civic.player.wallet,0,'failed purchase must not create debt');
assert.equal(t.shelves(shop).bread,before,'failed purchase must not take stock');
const cafe=t.place('cafe'), resident=t.villagers[0];
cafe.stock={bread:1,coffee:1,eggs:0,milk:0,veg:0,pie:0};
resident.wallet=100; resident.hunger=90; resident.step={activity:'having breakfast'};
const mealWallet=resident.wallet, mealTill=cafe.till, mealTax=t.civic.treasury, mealCount=t.stats.meals;
t.eatOut(resident,'cafe');
assert.match(resident.activity,/flat white and toast/,'the only fully stocked recipe is the one served');
assert.equal(cafe.stock.bread,0,'the meal consumes its bread');
assert.equal(cafe.stock.coffee,0,'the meal consumes its coffee');
assert.equal(resident.wallet,mealWallet-8,'the diner pays the listed menu price');
assert.equal(cafe.till,mealTill+7.2,'the cafe retains its post-tax sale');
assert.equal(t.civic.treasury,mealTax+0.8,'sales tax is recorded');
assert.equal(t.stats.meals,mealCount+1,'successful service records one meal');
assert.equal(t.stats.foodConsumed.bread,1);
assert.equal(t.stats.foodConsumed.coffee,1);
const noMealWallet=resident.wallet, noMealCount=t.stats.meals, noMealStock={...cafe.stock};
t.eatOut(resident,'cafe');
assert.equal(resident.wallet,noMealWallet,'a failed service does not charge the customer');
assert.equal(t.stats.meals,noMealCount,'a failed service does not create a meal');
assert.deepEqual(cafe.stock,noMealStock,'a failed service consumes no ingredients');
const menuWallet=t.civic.player.wallet;
t.civic.player.wallet=100;
cafe.stock={coffee:1};
const menu=placePanel(t,'cafe');
assert.match(menu.body,/Espresso · \$4 · in stock/,'the café panel lists stocked menu items');
assert.match(menu.body,/Toast · \$5 · sold out/,'the café panel shows unavailable items');
const espresso=menu.actions.find(action=>action.label==='Order Espresso ($4)');
assert(espresso,'the café panel offers an order action for stocked items');
espresso.run();
assert.equal(t.civic.player.wallet,96,'ordering from the café menu charges the listed price');
assert.equal(cafe.stock.coffee,0,'ordering from the café menu consumes its ingredients');
t.civic.player.wallet=menuWallet;
console.log('PASS: finite local trades, bank transfers, stock and insufficient funds');